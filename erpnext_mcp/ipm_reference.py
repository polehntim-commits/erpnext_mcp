"""The IPM reference book the farm_app carried, ported as data with its sources intact.

WHAT THIS IS AND WHY IT IS NOT A SEEDER. Everything here is a published fact
about an organism or a product — a base temperature, an IRAC group, a
pre-harvest interval, what spinetoram does to a lacewing. None of it is a fact
about anybody's farm, so none of it belongs in a DocType that an operator owns
and corrects. `agronomy_seed.py` lays down the starting book of things a farm
edits; this module is the opposite kind of data, and it is read, never written.

WHY IT HAD TO BE PORTED AT ALL. The farm_app's crop-protection tables were
assembled over two seasons out of UC IPM, the PNW handbooks, IRAC and FRAC code
lists and the Koppert side-effects database, and the assembly — which product is
in which group, and what each one costs the natural enemies — is the part that is
expensive to redo and impossible to reconstruct from the schema. `erpnext_mcp`
already has crop-level PHI floors; it had nothing at product level, and nothing
at all on beneficial toxicity.

THE BENEFICIAL TOXICITY TABLE IS THE HALF THAT IS USUALLY MISSING, and it is
the reason this module is worth its size. Every product label states a PHI and an
REI because the law requires it; almost none states what the product does to the
predators already working the block. A farm that sprays a pyrethroid for one
aphid flush and loses its predatory mites has bought a spider mite outbreak in
August, and the only place that consequence is written down is a table like this
one.

EVERY FIGURE CARRIES ITS SOURCE AND NONE OF THEM IS A LABEL. `data_source` names
where a toxicity score came from; `SOURCES` names the works the whole book was
built from. The rates and intervals here are RESEARCH REFERENCES: the label in
the operator's hand governs, it varies by state and formulation, and it changes.
Nothing in this app applies these numbers to a decision on its own.
"""

