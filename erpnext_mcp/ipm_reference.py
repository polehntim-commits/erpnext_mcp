# LOOKUP
#
# MATCHING IS CASE-INSENSITIVE AND WHITESPACE-TOLERANT AND NOTHING MORE. No
# fuzzy matching, no stemming, no "did you mean". The farm_app had a fuzzy pest
# matcher and it was a persistent source of rows quietly attached to the wrong
# organism — 'Cherry Slug' and 'Pear Slug' are the same animal and 'Spider
# Mites' is two species, and a matcher confident enough to bridge those is
# confident enough to bridge things that must not be bridged. A miss here
# returns nothing, which a caller can see.
# ══════════════════════════════════════════════════════════════════════════

#: Every table in the book, by the name a caller asks for.
TABLES = {
	"pest_models": PEST_MODELS,
	"beneficials": BENEFICIALS,
	"pest_damage": PEST_DAMAGE,
	"beneficial_activity": BENEFICIAL_ACTIVITY,
	"pesticide_efficacy": PESTICIDE_EFFICACY,
	"beneficial_toxicity": BENEFICIAL_TOXICITY,
	"pesticide_products": PESTICIDE_PRODUCTS,
	"pesticide_labels": PESTICIDE_LABELS,
}


def _key(value) -> str:
	return " ".join(str(value or "").split()).casefold()


def _match(row: dict, field: str, wanted: str) -> bool:
	return _key(row.get(field)) == _key(wanted)


def table_names() -> tuple[str, ...]:
	"""Every table a caller may ask for, in a stable order."""
	return tuple(sorted(TABLES))


def summary() -> dict:
	"""How many rows each table holds — the shape of the book at a glance."""
	return {name: len(rows) for name, rows in sorted(TABLES.items())}


def pest_model(pest: str) -> dict:
	"""One pest's record, including its emergence model where it has one."""
	for row in PEST_MODELS:
		if _match(row, "name", pest):
			return dict(row)
	return {}


def beneficial(name: str) -> dict:
	"""One beneficial organism's record."""
	for row in BENEFICIALS:
		if _match(row, "name", name):
			return dict(row)
	return {}


def damage_profile(pest: str, crop: str = "") -> list[dict]:
	"""What this pest costs, on one crop or on all of them."""
	return [
		dict(row)
		for row in PEST_DAMAGE
		if _match(row, "pest", pest) and (not crop or _match(row, "crop", crop))
	]


def efficacy_against(pest: str) -> list[dict]:
	"""Every product with a recorded effect on this pest, best first.

	Sorted by efficacy so the first row is the most effective and NOT
	necessarily the one to use — the resistance risk and what it costs the
	beneficials are both on the row for exactly that reason.
	"""
	rows = [dict(row) for row in PESTICIDE_EFFICACY if _match(row, "pest", pest)]
	return sorted(rows, key=lambda row: float(row.get("efficacy") or 0), reverse=True)


def toxicity_of(product: str) -> list[dict]:
	"""What one product does to every beneficial on file, worst first."""
	rows = [dict(row) for row in BENEFICIAL_TOXICITY if _match(row, "product", product)]
	return sorted(rows, key=lambda row: float(row.get("toxicity_score") or 0), reverse=True)


def labels_for(product_or_reg: str, crop: str = "") -> list[dict]:
	"""The label rows for a product, looked up by name OR registration number.

	Both are accepted because the two identifiers turn up in different places:
	a spray record carries the product name a crew used, and an inspection asks
	for the EPA registration number.
	"""
	regs = {
		_key(row.get("epa_reg_number"))
		for row in PESTICIDE_PRODUCTS
		if _match(row, "product", product_or_reg) or _match(row, "epa_reg_number", product_or_reg)
	}
	if not regs:
		regs = {_key(product_or_reg)}
	return [
		dict(row)
		for row in PESTICIDE_LABELS
		if _key(row.get("epa_reg_number")) in regs and (not crop or _match(row, "crop", crop))
	]


def product(product_or_reg: str) -> dict:
	"""One product, by name or by registration number."""
	for row in PESTICIDE_PRODUCTS:
		if _match(row, "product", product_or_reg) or _match(row, "epa_reg_number", product_or_reg):
			return dict(row)
	return {}


def rotation_partners(product_or_reg: str, pest: str) -> list[dict]:
	"""Products effective on the same pest from a DIFFERENT mode-of-action group.

	This is the question a resistance-management plan actually asks, and the
	reason `moa_group` is carried on every efficacy row. Two products that work
	equally well and share a group are one product as far as resistance is
	concerned, so same-group alternatives are excluded rather than ranked lower —
	including them would let a rotation be built out of one chemistry.

	A product with no recorded group returns nothing, which is the honest answer:
	a rotation cannot be checked against an unknown.
	"""
	own = {
		str(row.get("moa_group") or "").strip()
		for row in PESTICIDE_EFFICACY
		if _match(row, "product", product_or_reg) and _match(row, "pest", pest)
	}
	own = {group for group in own if group}
	if not own:
		return []
	return [
		row
		for row in efficacy_against(pest)
		if not _match(row, "product", product_or_reg)
		and str(row.get("moa_group") or "").strip()
		and str(row.get("moa_group") or "").strip() not in own
	]
