"""Tax form PDFs — the arithmetic of v0.34.0 drawn on the face of the form.

v0.36.0. `form_generators.py` computes what goes in each box. This draws the
boxes, in the official numbering and roughly the official arrangement, and puts
the computed value in each one. Same contract as the generators: PURE
FUNCTIONS. No database reads, no attachment writing, no side effects — a form
dict and two blocks of identifying text go in, PDF bytes come out, and the
whole thing can be checked against a fixture.

WHAT THESE ARE, SAID PLAINLY AND SAID ON EVERY PAGE. A working copy. An
official Copy A of a W-2 or a 1099 is printed in a specific red ink that the
IRS's scanners drop out, and no laser printer produces it; Oregon's and
Washington's returns are filed through Frances Online and ESD's portal, not on
paper this app made. So every page carries the header note and a disclaimer
block naming the agency and its real filing channel. These pages are for the
farmer's records, for a review before filing, and for keying the numbers into
the portal that does the filing — nothing else. Rendering one is not a filing
and changes no form's status.

THE FORM DATA IS THE RECORD; THE ARGUMENTS ONLY FILL HOLES. `form_data` was
computed and stored once, at generation, and it already carries the employer
and recipient blocks as they were then. `company_info` and the subject block
are consulted ONLY where `form_data` has nothing — an address that was never on
the Company when the form was generated, for instance. A renderer that
preferred today's arguments would print a form that disagrees with the record
it claims to render, which is the exact failure `taxforms.py` stores
`form_data_json` to avoid.

REPORTLAB IS OPTIONAL AT IMPORT TIME, like shapely, h3 and segno before it. A
bench without it loses exactly two tools — `render_tax_form_pdf` and
`bulk_render_tax_form_pdfs` — which say so by name with the pip command to fix
it, rather than failing to load the other three hundred and twenty-six. Every
generator and every other tax-form tool works without it: the numbers are the
deliverable and the page is a convenience.

TWO DELIBERATE CHOICES IN THE OUTPUT.

  * **No stream compression.** These pages are a few kilobytes and an
    uncompressed content stream is one a person can `grep` and `diff` — the
    same judgement `render/pdf.py` made, and it is what lets a test assert that
    a box value actually reached the page rather than that a renderer ran.
  * **Text is folded to ASCII.** The generators write prose with em dashes and
    curly quotes; the base-14 fonts here are WinAnsi and a stray character
    outside it is an exception at draw time rather than a mark on the page. So
    `_clean` folds the handful that occur and drops anything else, and a
    hyphen where an em dash was is a cost worth paying for a page that cannot
    fail to draw.
"""

