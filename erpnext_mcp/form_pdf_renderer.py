def _wa_employee_table(sheet: _Sheet, form_data: dict) -> None:
	"""The per-employee detail, repeating its header row on every page.

	A row is never split across a page break: half a wage figure at the foot of
	a page is how a number gets lost without anybody noticing.
	"""
	rows = list(form_data.get("employees") or [])

	def header() -> None:
		sheet.room_for(16 + 16)
		head_top = sheet.top
		sheet.fill_rect(MARGIN, head_top, CONTENT_WIDTH, 16)
		x = MARGIN
		for label, width, _key, kind in _WA_COLUMNS:
			sheet.rect(x, head_top, width, 16)
			if kind == "text":
				sheet.text(x + 4, head_top + 11, label, FONT_LABEL_BOLD, SIZE_LABEL)
			else:
				sheet.text(x + width - 4, head_top + 11, label, FONT_LABEL_BOLD, SIZE_LABEL, align="right")
			x += width
		sheet.top = head_top + 16

	header()
	if not rows:
		sheet.room_for(16)
		row_top = sheet.top
		sheet.rect(MARGIN, row_top, CONTENT_WIDTH, 16)
		sheet.text(MARGIN + 4, row_top + 11.5, "No Washington wages in this quarter.", FONT_LABEL, SIZE_SMALL)
		sheet.top = row_top + 16
		return

	for row in rows:
		if sheet.top + 16 > FOOTER_LIMIT:
			sheet.page_break()
			header()
		row_top = sheet.top
		x = MARGIN
		for _label, width, key, kind in _WA_COLUMNS:
			if kind == "money":
				value, align = _money(row.get(key)), "right"
			elif kind == "whole":
				value, align = _whole(row.get(key)), "right"
			elif key == "ssn_display":
				value, align = _bare_ssn(row.get(key)) or "XXX-XX-____", "left"
			else:
				value, align = _clean(row.get(key) or ""), "left"
			sheet.box(x, row_top, width, 16, "", value, value_size=7.5, value_align=align)
			x += width
		sheet.top = row_top + 16

	# The totals row, kept with at least one data row above it.
	if sheet.top + 16 > FOOTER_LIMIT:
		sheet.page_break()
		header()
	row_top = sheet.top
	totals = {
		"employee_name": f"TOTAL - {len(rows)} employee(s)",
		"hours": form_data.get("total_hours"),
		"wages": form_data.get("total_wages"),
		"taxable_wages": form_data.get("total_taxable_wages"),
		"excess_wages": form_data.get("total_excess_wages"),
	}
	sheet.fill_rect(MARGIN, row_top, CONTENT_WIDTH, 16, grey=0.93)
	x = MARGIN
	for _label, width, key, kind in _WA_COLUMNS:
		if kind == "money":
			value, align = _money(totals.get(key)), "right"
		elif kind == "whole":
			value, align = _whole(totals.get(key)), "right"
		else:
			value, align = _clean(totals.get(key) or ""), "left"
		sheet.box(x, row_top, width, 16, "", value, value_size=7.5, value_align=align, value_font=FONT_VALUE)
		x += width
	sheet.top = row_top + 16


