def render_w2_pdf(form_data: dict, company_info: dict, employee_info: dict) -> bytes:
	"""Render a W-2 Wage and Tax Statement PDF.

	Produces Copy B (for employee) layout with all boxes filled.

	Args:
		form_data: What `form_generators.generate_w2_data` returned.
		company_info: The employer block, consulted only where `form_data` is
			silent — `name`, `ein`, `address`.
		employee_info: The recipient block, same rule — `employee_name`,
			`ssn_display` or `ssn_last4`, `address`.

	Returns:
		PDF bytes. One page of form face, plus however many the notes take.
	"""
	form_data = dict(form_data or {})
	year = form_data.get("tax_year") or ""
	sheet = _sheet_for("W-2", form_data, f"Wage and Tax Statement {year}")

	employer = _employer(form_data, company_info)
	block = dict(form_data.get("employee") or {})
	info = dict(employee_info or {})
	name = _first(block.get("name"), info.get("employee_name"), info.get("name"), block.get("employee"))
	ssn = _first(block.get("ssn_display"), info.get("ssn_display"))
	if not ssn:
		last4 = str(info.get("ssn_last4") or "").strip()[-4:]
		ssn = f"XXX-XX-{last4}" if last4 else "XXX-XX-____  (no SSN on file)"
	address = _address_lines(_first(block.get("address"), info.get("address")), limit=2)

	sheet.masthead(
		"Form W-2",
		"Wage and Tax Statement",
		str(year),
		W2_COPY,
	)

	# The face is a TEN-ROW GRID of 26 points, and both halves are cut to it.
	# The left column is the identifying half (boxes a to f) and the right is the
	# money, two boxes wide, in the real form's numbering. The two columns end on
	# the same rule because a form whose halves stop at different heights reads
	# as a form with something missing from the shorter one.
	top = sheet.top
	row_h = 26.0
	rows = 10
	face_height = row_h * rows
	left_w = 250.0
	col_w = (CONTENT_WIDTH - left_w) / 2
	col1 = MARGIN + left_w
	col2 = col1 + col_w

	left_boxes = (
		(30.0, "a  Employee's social security number", [ssn], FONT_VALUE, SIZE_VALUE),
		(30.0, "b  Employer identification number (EIN)", [employer["ein"]], FONT_VALUE, SIZE_VALUE),
		(
			64.0,
			"c  Employer's name, address, and ZIP code",
			[employer["name"], *employer["address"]][:3] or ["(not recorded on this site)"],
			FONT_PLAIN,
			8.0,
		),
		(28.0, "d  Control number", [str(form_data.get("control_number") or "")], FONT_VALUE, SIZE_VALUE),
		(36.0, "e  Employee's first name and initial, last name, and suffix", [name], FONT_VALUE, SIZE_VALUE),
		(
			72.0,
			"f  Employee's address and ZIP code",
			address or ["(not recorded on this site)"],
			FONT_PLAIN,
			8.0,
		),
	)
	offset = 0.0
	for height, label, value, font, size in left_boxes:
		sheet.box(MARGIN, top + offset, left_w, height, label, value, value_font=font, value_size=size)
		offset += height

	money_rows = (
		(
			"1  Wages, tips, other compensation",
			"box1_wages",
			"2  Federal income tax withheld",
			"box2_federal_income_tax_withheld",
		),
		(
			"3  Social security wages",
			"box3_social_security_wages",
			"4  Social security tax withheld",
			"box4_social_security_tax_withheld",
		),
		(
			"5  Medicare wages and tips",
			"box5_medicare_wages",
			"6  Medicare tax withheld",
			"box6_medicare_tax_withheld",
		),
		("7  Social security tips", "box7_social_security_tips", "8  Allocated tips", "box8_allocated_tips"),
		("9", None, "10  Dependent care benefits", "box10_dependent_care_benefits"),
		("11  Nonqualified plans", "box11_nonqualified_plans", None, None),
	)
	for index, (left_label, left_key, right_label, right_key) in enumerate(money_rows):
		row_top = top + index * row_h
		if left_key:
			sheet.money_box(col1, row_top, col_w, row_h, left_label, form_data.get(left_key))
		else:
			sheet.box(col1, row_top, col_w, row_h, left_label, "")
		if right_label:
			if right_key:
				sheet.money_box(col2, row_top, col_w, row_h, right_label, form_data.get(right_key))
			else:
				sheet.box(col2, row_top, col_w, row_h, right_label, "")

	# Box 12 stacks four codes down the right; box 13's three ticks and box 14's
	# other-withholding lines sit beside it.
	codes = list(form_data.get("box12_codes") or [])
	for index in range(4):
		letter = "abcd"[index]
		entry = codes[index] if index < len(codes) else {}
		code = _clean(str((entry or {}).get("code") or ""))
		amount = _money((entry or {}).get("amount"), blank_zero=True) if entry else ""
		# 12d takes the last two rows so the right column closes on the same
		# rule as box 14 beside it.
		height = row_h * (2 if index == 3 else 1)
		sheet.box(
			col2,
			top + (5 + index) * row_h,
			col_w,
			height,
			f"12{letter}",
			f"{code}   {amount}".strip(),
			value_align="right",
		)

	# Box 13's three ticks STACK. Side by side they do not fit the column, and
	# the third one ends up drawn over box 12b — a tick in the wrong box on a
	# wage statement is not a cosmetic problem.
	box13 = dict(form_data.get("box13") or {})
	b13_top = top + 6 * row_h
	sheet.box(col1, b13_top, col_w, row_h * 2, "13", "")
	for index, (label, key) in enumerate(
		(
			("Statutory employee", "statutory_employee"),
			("Retirement plan", "retirement_plan"),
			("Third-party sick pay", "third_party_sick_pay"),
		)
	):
		sheet.checkbox(col1 + 5, b13_top + 12 + index * 13, label, bool(box13.get(key)), size=6.5)

	box14 = list(form_data.get("box14_other") or [])
	fourteen = [f"{item.get('code', '')}  {_money(item.get('amount'))}" for item in box14[:3]]
	if len(box14) > 3:
		fourteen = [*fourteen[:2], f"+ {len(box14) - 2} more, see notes"]
	sheet.box(col1, top + 8 * row_h, col_w, row_h * 2, "14  Other", fourteen, value_size=7.5)

	sheet.top = top + face_height + 6

	# Boxes 15 to 20, one row per state the worker had wages in.
	_w2_state_table(sheet, form_data)

	extra = []
	if box14:
		extra.append(
			"Box 14 carries the state levies that are withheld but are not income tax: "
			+ "; ".join(
				f"{item.get('code', '')} {_money(item.get('amount'))} ({item.get('description', '')})"
				for item in box14
			)
			+ "."
		)
	extra.append(
		"The social security number is printed as four digits because this system stores "
		"four and never nine. Complete the rest from the employee's I-9 or Social Security "
		"card before the copy is furnished."
	)
	_notes(sheet, form_data, extra)
	return sheet.render()


def _w2_state_table(sheet: _Sheet, form_data: dict) -> None:
	"""Boxes 15 through 20 across the full width, one row per state."""
	# Every width is set so its box number and label fit on ONE line. A header
	# that wraps loses the two spaces after the box number, and "20 Locality
	# name" is not what the form calls box 20.
	columns = (
		("15  State", 44.0, "box15_state", "text"),
		("Employer's state ID number", 100.0, "box15_employer_state_id", "text"),
		("16  State wages, tips, etc.", 92.0, "box16_state_wages", "money"),
		("17  State income tax", 78.0, "box17_state_income_tax", "money"),
		("18  Local wages, tips, etc.", 88.0, "box18_local_wages", "money"),
		("19  Local income tax", 76.0, "box19_local_income_tax", "money"),
		("20  Locality name", 62.0, "box20_locality_name", "text"),
	)
	rows = list(form_data.get("state_boxes") or [])
	sheet.room_for(20 + 20 * max(1, len(rows)))

	top = sheet.top
	x = MARGIN
	for label, width, _key, _kind in columns:
		sheet.rect(x, top, width, 20)
		for index, line in enumerate(sheet.wrap(label, width - 5, FONT_LABEL, SIZE_LABEL)[:2]):
			sheet.text(x + 3, top + SIZE_LABEL + 2.5 + index * 7, line, FONT_LABEL, SIZE_LABEL)
		x += width

	if not rows:
		rows = [{}]
	for row_index, row in enumerate(rows):
		row_top = top + 20 + row_index * 20
		x = MARGIN
		for _label, width, key, kind in columns:
			value = _money(row.get(key)) if kind == "money" else _clean(row.get(key) or "")
			sheet.box(
				x,
				row_top,
				width,
				20,
				"",
				value,
				value_size=8.0,
				value_align="right" if kind == "money" else "left",
			)
			x += width
	sheet.top = top + 20 + 20 * len(rows)


