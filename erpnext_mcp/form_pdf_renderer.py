def _employer(form_data: dict, company_info: dict, key: str = "employer") -> dict:
	"""The employer block as it goes on the page: record first, argument second."""
	block = dict(form_data.get(key) or {})
	info = dict(company_info or {})
	ein = _first(block.get("ein"), info.get("ein"))
	return {
		"name": _first(block.get("name"), info.get("name")),
		"ein": ein or "__-_______  (set the company's Tax ID)",
		"address": _address_lines(_first(block.get("address"), info.get("address"))),
	}


def _period_line(form_data: dict) -> str:
	start = _first(form_data.get("period_start"))
	end = _first(form_data.get("period_end"))
	if start and end:
		return f"Period covered: {start} to {end}"
	return ""


def _notes(sheet: _Sheet, form_data: dict, extra: list[str] | None = None) -> None:
	"""The section a reader is told to read first, at the foot of every form.

	The generator's `warnings` are reproduced verbatim and in full. They are the
	only place a form says which of its figures is a floor rather than a figure,
	and a page that dropped them would look more certain than the arithmetic
	behind it.
	"""
	sheet.heading("Before this form is filed")
	for note in extra or []:
		sheet.paragraph(note)
		sheet.spacer(2)

	warnings = [w for w in (form_data.get("warnings") or []) if str(w or "").strip()]
	if warnings:
		sheet.paragraph(
			f"The generator raised {len(warnings)} note(s) on this form. Each one names a "
			"figure it had to assume rather than know:",
			font=FONT_LABEL_BOLD,
		)
		sheet.spacer(2)
		sheet.bullets(warnings)
	else:
		sheet.paragraph(
			"The generator raised no notes on this form: every figure was computed from "
			"payroll records held in this system, with nothing assumed."
		)


def _sheet_for(form_type: str, form_data: dict, what: str) -> _Sheet:
	require()
	year = form_data.get("tax_year") or ""
	quarter = form_data.get("quarter") or ""
	label = f"{form_type} {year}{' ' + str(quarter) if quarter else ''}".strip()
	return _Sheet(form_type, f"Form {label} - working copy", what)


