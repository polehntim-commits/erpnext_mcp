# ── text and money ──────────────────────────────────────────────────────────


def _clean(text) -> str:
	"""Fold prose to something the base-14 fonts can draw. Never raises."""
	if text is None:
		return ""
	out = str(text)
	for character, replacement in _FOLD.items():
		out = out.replace(character, replacement)
	return "".join(character if 32 <= ord(character) < 127 else " " for character in out)


def _money(value, blank_zero: bool = False) -> str:
	"""A figure as it belongs in a box: grouped, two places, never a bare int."""
	try:
		amount = float(value or 0)
	except (TypeError, ValueError):
		return ""
	if blank_zero and abs(amount) < 0.005:
		return ""
	return f"{amount:,.2f}"


def _whole(value) -> str:
	try:
		return f"{round(float(value or 0)):,}"
	except (TypeError, ValueError):
		return ""


def _first(*values) -> str:
	"""The first of several sources that actually says something."""
	for value in values:
		text = str(value or "").strip()
		if text:
			return text
	return ""


def _bare_ssn(display) -> str:
	"""`XXX-XX-1234`, without the generator's parenthetical.

	`_ssn_display` returns `XXX-XX-____  (no SSN on file)`, which is exactly
	right in a tool result and two and a half times too wide for a column in a
	wage-detail table. The parenthetical is not lost: the generator raises a
	warning naming every employee whose number is missing, and it prints in full
	in the notes.
	"""
	return str(display or "").split("  (")[0].strip()


def _address_lines(address: str, limit: int = 3) -> list[str]:
	"""One stored address string as the two or three lines a box has room for.

	Split on commas, because that is how every address on this site is stored —
	`_employee_info` in `tools/taxforms.py` joins the I-9's street, city and
	state/ZIP with them. A caller who stored newlines gets those honoured too.
	"""
	raw = str(address or "").replace("\n", ",")
	parts = [part.strip() for part in raw.split(",") if part.strip()]
	if not parts:
		return []
	if len(parts) <= limit:
		return parts
	# Fold the overflow into the last line rather than dropping it: a ZIP code
	# that vanished because an address had one comma too many is the kind of
	# quiet wrongness a printed form should never have.
	return [*parts[: limit - 1], ", ".join(parts[limit - 1 :])]


# ── the sheet ───────────────────────────────────────────────────────────────


class _Sheet:
	"""One form: a grid of labelled boxes, then a flowing notes section.

	Geometry is TOP-DOWN. Every `top` argument is points from the top edge of
	the page, because that is how a form is described — "box 1 is an inch from
	the top" — and converting once here beats inverting a coordinate in forty
	call sites. `self.top` is the cursor the flowing half advances.

	v0.91.0. THE PAGE FURNITURE IS NOW AN ARGUMENT, AND THE DEFAULTS ARE THE SIX
	TAX FORMS' EXACTLY. `pay_stub_pdf.py` draws on this class because the boxes,
	the clipping, the wrap and the pagination are the same problem — but a pay
	stub is NOT a working copy of anything. It is the statement of earnings an
	employer is required to hand a worker (ORS 652.610, RCW 49.46.020), it is
	produced from the slip that was actually paid, and stamping "NOT AN OFFICIAL
	FORM - this is not a filing" across it would be a false statement about the
	one document on this site that IS the record it looks like.

	So `header_note`, `page_label` and `footer` may be given, and every one of
	them defaults to what the tax forms have always drawn. A caller that passes
	none gets a byte-identical page to the one v0.36.0 produced, which is what
	`Disclaimers` in `test_tax_form_pdfs.py` goes on asserting.
	"""

	def __init__(
		self,
		form_type: str,
		title: str,
		subject: str,
		header_note: str = "",
		page_label: str = "",
		footer: str = "",
	):
		self._buffer = io.BytesIO()
		self._canvas = rl_canvas.Canvas(
			self._buffer,
			pagesize=(PAGE_WIDTH, PAGE_HEIGHT),
			# See the module docstring: a few kilobytes, and a stream a person
			# can read is a stream a test can assert against.
			pageCompression=0,
		)
		self._canvas.setTitle(_clean(title))
		self._canvas.setSubject(_clean(subject))
		self._canvas.setAuthor(PRODUCER)
		self._canvas.setCreator(PRODUCER)
		self._form_type = form_type
		self._channel = FILING_CHANNEL.get(form_type, "")
		self._header_note = header_note or HEADER_NOTE
		self._page_label = page_label or f"{form_type} - working copy"
		self._footer = footer or DISCLAIMER.format(channel=self._channel)
		self._page_number = 0
		self.top = BODY_TOP
		self._begin_page()

	# -- primitives ----------------------------------------------------------
	def _y(self, top: float) -> float:
		return PAGE_HEIGHT - top

	def width_of(self, text: str, font: str, size: float) -> float:
		return self._canvas.stringWidth(_clean(text), font, size)

	def clip(self, text: str, width: float, font: str, size: float) -> str:
		"""Shorten `text` until it fits, marking that it was shortened.

		Every value drawn inside a box goes through this. A figure that runs
		past its own rule and over the next box's is worse than a truncated one:
		it looks like it belongs to the column it has spilled into.
		"""
		body = _clean(text)
		if self.width_of(body, font, size) <= width:
			return body
		while body and self.width_of(body + ".", font, size) > width:
			body = body[:-1]
		return body + "."

	def text(
		self,
		x: float,
		baseline_top: float,
		text: str,
		font: str = FONT_LABEL,
		size: float = SIZE_LABEL,
		align: str = "left",
	) -> None:
		"""One string, its BASELINE at `baseline_top` points from the page top."""
		body = _clean(text)
		if not body:
			return
		self._canvas.setFont(font, size)
		if align == "right":
			self._canvas.drawRightString(x, self._y(baseline_top), body)
		elif align == "center":
			self._canvas.drawCentredString(x, self._y(baseline_top), body)
		else:
			self._canvas.drawString(x, self._y(baseline_top), body)

	def rect(self, x: float, top: float, width: float, height: float, line_width: float = 0.6) -> None:
		self._canvas.setLineWidth(line_width)
		self._canvas.rect(x, self._y(top + height), width, height, stroke=1, fill=0)

	def line(self, x1: float, top: float, x2: float, line_width: float = 0.5) -> None:
		self._canvas.setLineWidth(line_width)
		self._canvas.line(x1, self._y(top), x2, self._y(top))

	def fill_rect(self, x: float, top: float, width: float, height: float, grey: float = 0.9) -> None:
		self._canvas.setFillGray(grey)
		self._canvas.rect(x, self._y(top + height), width, height, stroke=0, fill=1)
		self._canvas.setFillGray(0)

	# -- boxes ---------------------------------------------------------------
	def box(
		self,
		x: float,
		top: float,
		width: float,
		height: float,
		label: str = "",
		value="",
		value_font: str = FONT_VALUE,
		value_size: float = SIZE_VALUE,
		value_align: str = "left",
		label_font: str = FONT_LABEL,
	) -> None:
		"""One numbered box: a rule around it, its label small at the top-left,
		its value beneath. `value` may be a string or a list of lines.

		The label WRAPS and the value CLIPS, and the asymmetry is deliberate: a
		label is prose that can take a second line, and a figure that took a
		second line would read as two figures.
		"""
		self.rect(x, top, width, height)
		lines = value if isinstance(value, (list, tuple)) else [value]
		lines = [_clean(line) for line in lines if str(line or "").strip()]

		if label:
			room = height - ((value_size + 6.0) if lines else 4.0)
			allowed = max(1, min(3, int(room / (SIZE_LABEL + 1.5))))
			for index, part in enumerate(self.wrap(label, width - 6, label_font, SIZE_LABEL)[:allowed]):
				self.text(
					x + 3,
					top + SIZE_LABEL + 2.5 + index * (SIZE_LABEL + 1.5),
					part,
					label_font,
					SIZE_LABEL,
				)

		if not lines:
			return
		leading = value_size + 2.0
		first = top + height - 4.5 - leading * (len(lines) - 1)
		for index, line in enumerate(lines):
			baseline = first + leading * index
			body = self.clip(line, width - 8, value_font, value_size)
			if value_align == "right":
				self.text(x + width - 4, baseline, body, value_font, value_size, align="right")
			elif value_align == "center":
				self.text(x + width / 2, baseline, body, value_font, value_size, align="center")
			else:
				self.text(x + 4, baseline, body, value_font, value_size)

	def money_box(self, x: float, top: float, width: float, height: float, label: str, value) -> None:
		"""A box whose value is a figure, and figures are right-aligned."""
		self.box(x, top, width, height, label, _money(value), value_align="right")

	def checkbox(self, x: float, top: float, label: str, ticked: bool, size: float = 7.5) -> float:
		"""A tick box with its label to the right. Returns the width consumed."""
		self.rect(x, top, size, size, line_width=0.6)
		if ticked:
			self._canvas.setLineWidth(1.1)
			self._canvas.line(x + 1.4, self._y(top + size - 1.4), x + size - 1.4, self._y(top + 1.4))
			self._canvas.line(x + 1.4, self._y(top + 1.4), x + size - 1.4, self._y(top + size - 1.4))
		self.text(x + size + 3, top + size - 0.8, label, FONT_LABEL, SIZE_SMALL)
		return size + 6 + self.width_of(label, FONT_LABEL, SIZE_SMALL)

	def ink(
		self, x: float, baseline_top: float, image_bytes: bytes, max_width: float, max_height: float
	) -> bool:
		"""Draw a signature capture sitting ON a ruled line. True if it landed.

		THE CROPPING IS `pdf_signing.ink_only`, NOT A SECOND ONE. That function
		already knows what a capture from this app's pad looks like — a mostly
		white PNG with a stroke somewhere in it — and trims to the stroke so a
		signature drawn in the corner of a canvas does not render as a dot in the
		middle of a box. A second implementation here would be a second answer to
		"where is the ink", and the two would disagree on the same picture.

		ANCHORED TO THE BASELINE AND GROWING UPWARD, because that is where
		handwriting goes on a printed rule. Scaled to fit both bounds, never
		stretched: a signature squashed to fill a box is not the mark that was
		made.

		FALSE RATHER THAN AN EXCEPTION on a bench without Pillow or reportlab's
		image reader, or on bytes that hold no ink. The caller draws the ruled
		line either way and the page says the row is unsigned, which is a true
		statement about a sheet somebody has to go and finish.
		"""
		from . import pdf_signing

		prepared = pdf_signing.ink_only(image_bytes)
		if not prepared:
			return False
		try:
			from reportlab.lib.utils import ImageReader
		except ImportError:  # pragma: no cover - a bench without reportlab cannot be here
			return False
		png, ink_width, ink_height = prepared
		if ink_width <= 0 or ink_height <= 0:
			return False
		scale = min(max_width / ink_width, max_height / ink_height)
		width, height = ink_width * scale, ink_height * scale
		try:
			self._canvas.drawImage(
				ImageReader(io.BytesIO(png)),
				x,
				self._y(baseline_top),
				width=width,
				height=height,
				mask="auto",
			)
		except Exception:  # pragma: no cover - an image reportlab will not decode
			return False
		return True

	# -- the flowing half ----------------------------------------------------
	def masthead(self, title: str, form_line: str, right: str, copy_line: str = "") -> None:
		"""The band every form opens with: what it is, for when, and which copy."""
		self.text(MARGIN, self.top + SIZE_TITLE, title, FONT_LABEL_BOLD, SIZE_TITLE)
		self.text(
			PAGE_WIDTH - MARGIN,
			self.top + SIZE_TITLE,
			right,
			FONT_LABEL_BOLD,
			SIZE_TITLE,
			align="right",
		)
		self.top += SIZE_TITLE + 3
		self.text(MARGIN, self.top + SIZE_SUBTITLE, form_line, FONT_LABEL, SIZE_SUBTITLE)
		self.top += SIZE_SUBTITLE + 2
		if copy_line:
			self.text(MARGIN, self.top + SIZE_SUBTITLE, copy_line, FONT_LABEL_BOLD, SIZE_SUBTITLE)
			self.top += SIZE_SUBTITLE + 2
		self.line(MARGIN, self.top + 2, PAGE_WIDTH - MARGIN, line_width=1.1)
		self.top += 8

	def heading(self, text: str) -> None:
		self.room_for(SIZE_HEADING + 14)
		self.top += 6
		self.text(MARGIN, self.top + SIZE_HEADING, text, FONT_LABEL_BOLD, SIZE_HEADING)
		self.top += SIZE_HEADING + 2
		self.line(MARGIN, self.top, PAGE_WIDTH - MARGIN, line_width=0.75)
		self.top += 5

	def paragraph(
		self, text: str, size: float = SIZE_SMALL, font: str = FONT_LABEL, indent: float = 0.0
	) -> None:
		for line in self.wrap(text, CONTENT_WIDTH - indent, font, size):
			self.room_for(size + 2.5)
			self.text(MARGIN + indent, self.top + size, line, font, size)
			self.top += size + 2.5

	def bullets(self, items, size: float = SIZE_SMALL) -> None:
		for item in items:
			lines = self.wrap(str(item), CONTENT_WIDTH - 12, FONT_LABEL, size)
			for index, line in enumerate(lines):
				self.room_for(size + 2.5)
				prefix = "- " if index == 0 else "  "
				self.text(MARGIN + 2, self.top + size, prefix + line, FONT_LABEL, size)
				self.top += size + 2.5
			self.top += 1.5

	def spacer(self, points: float = 5.0) -> None:
		self.top += points

	def wrap(self, text: str, width: float, font: str, size: float) -> list[str]:
		"""Greedy wrap measured in points, not guessed in characters.

		A line that already fits comes back UNTOUCHED, spacing and all. Wrapping
		splits on whitespace and rejoins with single spaces, which would quietly
		turn `1  Wages, tips, other compensation` — the real form's two spaces
		after a box number — into something that only looks like it.
		"""
		body = _clean(text)
		if not body:
			return []
		if "\n" not in body and self.width_of(body, font, size) <= width:
			return [body]
		lines: list[str] = []
		for paragraph in body.split("\n"):
			current = ""
			for word in paragraph.split():
				candidate = f"{current} {word}".strip()
				if current and self.width_of(candidate, font, size) > width:
					lines.append(current)
					current = word
				else:
					current = candidate
			lines.append(current)
		return [line for line in lines if line != ""] or [""]

	# -- pagination ----------------------------------------------------------
	def room_for(self, height: float) -> None:
		if self.top + height > FOOTER_LIMIT:
			self.page_break()

	def page_break(self) -> None:
		self._finish_page()
		self._canvas.showPage()
		self.top = BODY_TOP
		self._begin_page()

	def _begin_page(self) -> None:
		self._page_number += 1
		self.text(MARGIN, HEADER_BASELINE, self._header_note, FONT_LABEL_BOLD, SIZE_SMALL)
		self.text(
			PAGE_WIDTH - MARGIN,
			HEADER_BASELINE,
			f"{self._page_label} - page {self._page_number}",
			FONT_LABEL,
			SIZE_SMALL,
			align="right",
		)
		self.line(MARGIN, HEADER_BASELINE + 4, PAGE_WIDTH - MARGIN, line_width=0.75)

	def _finish_page(self) -> None:
		"""The footer band. Drawn last on every page, so a page cannot exist
		without it — including one that only exists because a table overflowed."""
		self.line(MARGIN, FOOTER_TOP - 6, PAGE_WIDTH - MARGIN, line_width=0.75)
		body = self._footer
		top = FOOTER_TOP
		for line in self.wrap(body, CONTENT_WIDTH, FONT_NOTE, 6.2)[:4]:
			self.text(MARGIN, top, line, FONT_NOTE, 6.2)
			top += 7.6

	def render(self) -> bytes:
		"""The whole document as PDF bytes. Callable once per sheet."""
		self._finish_page()
		self._canvas.showPage()
		self._canvas.save()
		return self._buffer.getvalue()


