#: Which renderer draws which form, and whether it needs a recipient block.
#: Same shape and the same reason as `form_generators.generate_form_data`: the
#: "which arguments does this form take" question belongs in one place rather
#: than repeated in every caller.
RENDERERS = {
	"W-2": render_w2_pdf,
	"1099-NEC": render_1099_nec_pdf,
	"941": render_941_pdf,
	"OR-WR": render_or_wr_pdf,
	"OQ": render_or_oq_pdf,
	"WA-ESD": render_wa_esd_pdf,
	"940": render_940_pdf,
	"W-3": render_w3_pdf,
}

#: The two forms whose renderer takes a third argument: the person it is about.
PER_RECIPIENT = ("W-2", "1099-NEC")


def render_form_pdf(
	form_type: str,
	form_data: dict,
	company_info: dict | None = None,
	subject_info: dict | None = None,
) -> bytes:
	"""Route to the right renderer. The one entry point a tool needs."""
	require()
	renderer = RENDERERS.get(form_type)
	if renderer is None:
		raise ToolError(
			f"no PDF layout for form type {form_type!r}. Known forms: {', '.join(sorted(RENDERERS))}."
		)
	if form_type in PER_RECIPIENT:
		return renderer(form_data or {}, company_info or {}, subject_info or {})
	return renderer(form_data or {}, company_info or {})


def file_name_for(form_type: str, form_data: dict, subject: str = "") -> str:
	"""What the attached file is called. Sortable, and says what it is on sight."""
	parts = [str(form_type).replace("/", "-")]
	year = form_data.get("tax_year")
	if year:
		parts.append(str(year))
	quarter = form_data.get("quarter")
	if quarter:
		parts.append(str(quarter))
	if subject:
		parts.append("".join(c if c.isalnum() or c in "-_" else "-" for c in str(subject)).strip("-"))
	return "-".join(part for part in parts if part) + ".pdf"
